/**
 * Accepted upload formats, recognised from the first bytes of the file
 * (never from the client-supplied name or Content-Type).
 */
export type DetectedFileType = { contentType: string; extension: string };

const SIGNATURES: { bytes: number[]; type: DetectedFileType }[] = [
  { bytes: [0x25, 0x50, 0x44, 0x46, 0x2d], type: { contentType: "application/pdf", extension: "pdf" } }, // %PDF-
  { bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], type: { contentType: "image/png", extension: "png" } },
  { bytes: [0xff, 0xd8, 0xff], type: { contentType: "image/jpeg", extension: "jpg" } },
];

export function detectFileType(data: Uint8Array): DetectedFileType | null {
  for (const { bytes, type } of SIGNATURES) {
    if (data.length >= bytes.length && bytes.every((b, i) => data[i] === b)) return type;
  }
  return null;
}

/**
 * Display name only: the storage key is always generated by the server.
 * Keeps the last path segment, removes control and reserved characters.
 */
export function sanitizeFileName(raw: string | undefined, fallbackExtension: string): string {
  const base = (raw ?? "").split(/[\\/]/).pop() ?? "";
  const cleaned = base
    .normalize("NFC")
    .replace(/[\u0000-\u001f\u007f"<>|:*?]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120);
  if (!cleaned || cleaned === "." || cleaned === "..") return `document.${fallbackExtension}`;
  return cleaned;
}
